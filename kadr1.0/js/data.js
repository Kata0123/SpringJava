async function loadRandomMovies(n=50){
  const d=await loadMovies();
  const a=[...d.catalog,...d.featured];
  for(let i=a.length-1;i>0;i--){ const j=Math.random()*(i+1)|0; [a[i],a[j]]=[a[j],a[i]]; }
  return a.slice(0,n);
}
